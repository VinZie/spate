#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn credentials_only_go_to_the_playlist_origin() {
    let server = Server::start().await;
    let key = [0x42u8; 16];
    let iv = [0u8; 16];
    let segment = |i: usize| encrypt(&key, &iv, &plain_segment(i));
    // The site serves the master playlist and one segment; the variant, the
    // key and the other segments live on other origins.
    server.route(
        "http://site.example/hls/master.m3u8",
        Route::new("#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=1000\nhttp://cdn.example/v/index.m3u8\n", MPEGURL),
    );
    server.route(
        "http://cdn.example/v/index.m3u8",
        Route::public(
            "#EXTM3U\n#EXT-X-KEY:METHOD=AES-128,URI=\"http://keys.example/k.bin\",IV=0x0\n\
             #EXTINF:1,\ns0.ts\n\
             #EXTINF:1,\nhttp://site.example/hls/s1.ts\n\
             #EXTINF:1,\nhttp://site.example:8080/hls/s2.ts\n\
             #EXTINF:1,\nhttp://site.example/hls/s3.ts\n\
             #EXT-X-ENDLIST\n",
            MPEGURL,
        ),
    );
    server.route("http://keys.example/k.bin", Route::public(key.to_vec(), "application/octet-stream"));
    server.route("http://cdn.example/v/s0.ts", Route::public(segment(0), "video/mp2t"));
    server.route("http://site.example/hls/s1.ts", Route::new(segment(1), "video/mp2t"));
    server.route("http://site.example:8080/hls/s2.ts", Route::public(segment(2), "video/mp2t"));
    // Same origin, redirected to the CDN.
    server.route(
        "http://site.example/hls/s3.ts",
        Route { redirect: Some("http://cdn.example/v/s3.ts".into()), ..Route::new(Vec::new(), "video/mp2t") },
    );
    server.route(
        "http://cdn.example/v/s3.ts",
        Route { referer: Some("http://site.example/hls/s3.ts"), ..Route::public(segment(3), "video/mp2t") },
    );

    let dir = temp_dir("origin");
    let mut req = request("http://site.example/hls/master.m3u8".into(), &dir, None);
    req.headers.push(("Authorization".into(), "Bearer secret".into()));
    let outcome = hls::run(req, proxied(&server, 2), Arc::new(Progress::default()), CancellationToken::new())
        .await
        .expect("download succeeds");
    let Outcome::Completed { path, .. } = outcome else { panic!("expected completion, got {outcome:?}") };
    let expected: Vec<u8> = (0..4).flat_map(plain_segment).collect();
    assert!(std::fs::read(&path).unwrap() == expected, "output differs");

    let same_origin =
        ["http://site.example/hls/master.m3u8", "http://site.example/hls/s1.ts", "http://site.example/hls/s3.ts"];
    for same in same_origin {
        assert_eq!((server.hits(same), server.credentialed(same)), (1, 1), "{same}");
    }
    for other in [
        "http://cdn.example/v/index.m3u8",    // variant on another host
        "http://keys.example/k.bin",          // key
        "http://cdn.example/v/s0.ts",         // segment
        "http://site.example:8080/hls/s2.ts", // same host, another port
        "http://cdn.example/v/s3.ts",         // redirect target
    ] {
        assert_eq!((server.hits(other), server.credentialed(other)), (1, 0), "{other}");
    }
    assert_eq!(server.state.rejected.load(Ordering::SeqCst), 0, "the referer goes everywhere");
    let _ = std::fs::remove_dir_all(&dir);
}

#[tokio::test]
async fn public_playlists_may_not_point_at_local_addresses() {
    let server = Server::start().await;
    let loopback = server.url("/lan/a.ts");
    server.route(&loopback, Route::public(b"lan".to_vec(), "video/mp2t"));
    server.route("http://site.example/ok.ts", Route::new(b"ok".to_vec(), "video/mp2t"));
    server.route("http://localhost/x.ts", Route::public(b"local".to_vec(), "video/mp2t"));
    server.route(
        "http://site.example/r.ts",
        Route { redirect: Some("http://localhost/x.ts".into()), ..Route::new(Vec::new(), "video/mp2t") },
    );
    let cases = [
        ("segment", format!("#EXTINF:1,\nhttp://site.example/ok.ts\n#EXTINF:1,\n{loopback}\n")),
        ("key", "#EXT-X-KEY:METHOD=AES-128,URI=\"http://[::1]/k.bin\"\n#EXTINF:1,\nhttp://site.example/ok.ts\n".into()),
        ("variant", "#EXT-X-STREAM-INF:BANDWIDTH=1\nhttp://192.168.1.20/v.m3u8\n".into()),
        ("redirect", "#EXTINF:1,\nhttp://site.example/r.ts\n".into()),
    ];
    let dir = temp_dir("local");
    for (name, body) in cases {
        let url = format!("http://site.example/{name}.m3u8");
        server.route(&url, Route::new(format!("#EXTM3U\n{body}#EXT-X-ENDLIST\n"), MPEGURL));
        let err = run_err(request(url, &dir, None), proxied(&server, 2)).await;
        assert!(err.contains("may not point at a local network address"), "{name}: {err}");
        assert!(dir_entries(&dir).is_empty(), "{name}: {:?}", dir_entries(&dir));
    }
    // Checked before anything is downloaded; the local hosts never see a request.
    assert_eq!(server.hits("http://site.example/ok.ts"), 0);
    assert_eq!(server.hits(&loopback), 0);
    assert_eq!(server.hits("http://[::1]/k.bin"), 0);
    assert_eq!(server.hits("http://192.168.1.20/v.m3u8"), 0);

    // A playlist on the local network may use local addresses.
    server.route(
        "http://192.168.1.20/index.m3u8",
        Route::new(
            "#EXTM3U\n#EXTINF:1,\nhttp://10.0.0.5/a.ts\n#EXTINF:1,\nhttp://localhost/x.ts\n#EXT-X-ENDLIST\n",
            MPEGURL,
        ),
    );
    server.route("http://10.0.0.5/a.ts", Route::public(b"nas-".to_vec(), "video/mp2t"));
    let outcome = hls::run(
        request("http://192.168.1.20/index.m3u8".into(), &dir, None),
        proxied(&server, 2),
        Arc::new(Progress::default()),
        CancellationToken::new(),
    )
    .await
    .expect("local playlist downloads");
    let Outcome::Completed { path, .. } = outcome else { panic!("expected completion, got {outcome:?}") };
    assert_eq!(std::fs::read(&path).unwrap(), b"nas-local");
    let _ = std::fs::remove_dir_all(&dir);
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn oversized_segments_are_rejected() {
    let server = Server::start().await;
    const LIMIT: u64 = 256 * MIB;
    server.route("/big/a.ts", Route::new(plain_segment(0), "video/mp2t"));
    server.route("/big/declared.ts", Route::streamed(Streamed::Sized(LIMIT + 1)));
    server.route("/big/endless.ts", Route::streamed(Streamed::Endless));
    server.route("/big/whole.ts", Route::new(plain_segment(1), "video/mp2t"));
    let dir = temp_dir("oversized");
    for (name, entry) in [
        // Refused from its Content-Length, before the body is read.
        ("declared", "declared.ts".to_string()),
        // No length: refused once the limit is reached.
        ("endless", "endless.ts".to_string()),
        // Refused from the playlist alone.
        ("range", format!("#EXT-X-BYTERANGE:{}@0\nwhole.ts", LIMIT + 1)),
    ] {
        let url = server.url(&format!("/big/{name}.m3u8"));
        let playlist = format!("#EXTM3U\n#EXTINF:1,\na.ts\n#EXTINF:1,\n{entry}\n#EXT-X-ENDLIST\n");
        server.route(&format!("/big/{name}.m3u8"), Route::new(playlist, MPEGURL));
        let progress = Arc::new(Progress::default());
        let err = hls::run(request(url, &dir, None), options(2), progress.clone(), CancellationToken::new())
            .await
            .unwrap_err()
            .to_string();
        assert!(err.starts_with("HLS segment ") && err.ends_with(" is larger than 256 MiB"), "{name}: {err}");
        assert!(dir_entries(&dir).is_empty(), "{name}: {:?}", dir_entries(&dir));
        let received = progress.received();
        if name == "endless" {
            assert!(received >= LIMIT, "{name}: {received}");
        } else {
            assert!(received < 64 * MIB, "{name}: read {received} bytes");
        }
    }
    assert_eq!(server.hits("/big/whole.ts"), 0);
    let _ = std::fs::remove_dir_all(&dir);
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn segments_waiting_to_be_written_share_a_memory_limit() {
    const LIMIT: u64 = 128 * MIB;
    let server = Server::start().await;
    // The first segment never arrives, so everything fetched after it has to
    // wait in memory; the others never end.
    server.route("/buf/s0.ts", Route { hang: true, ..Route::new(Vec::new(), "video/mp2t") });
    let mut playlist = String::from("#EXTM3U\n#EXTINF:4,\ns0.ts\n");
    for i in 1..8 {
        server.route(&format!("/buf/s{i}.ts"), Route::streamed(Streamed::Endless));
        playlist.push_str(&format!("#EXTINF:4,\ns{i}.ts\n"));
    }
    playlist.push_str("#EXT-X-ENDLIST\n");
    server.route("/buf/index.m3u8", Route::new(playlist, MPEGURL));

    let dir = temp_dir("buffered");
    let progress = Arc::new(Progress::default());
    let cancel = CancellationToken::new();
    let task = tokio::spawn(hls::run(
        request(server.url("/buf/index.m3u8"), &dir, None),
        options(4),
        progress.clone(),
        cancel.clone(),
    ));

    // Wait until the download has buffered a good part of the limit and then
    // stops taking data in.
    let deadline = Instant::now() + Duration::from_secs(60);
    let (mut last, mut since) = (0, Instant::now());
    loop {
        tokio::time::sleep(Duration::from_millis(100)).await;
        let now = progress.received();
        assert!(now <= LIMIT + 4 * MIB, "buffered {now} bytes");
        if now != last {
            (last, since) = (now, Instant::now());
        } else if now >= 32 * MIB && since.elapsed() > Duration::from_secs(1) {
            break;
        }
        assert!(Instant::now() < deadline, "still receiving after {now} bytes");
    }
    assert!(!task.is_finished());

    cancel.cancel();
    let outcome = tokio::time::timeout(Duration::from_secs(5), task).await.expect("stops promptly").unwrap();
    assert!(matches!(outcome, Ok(Outcome::Paused)), "{outcome:?}");
    assert!(dir_entries(&dir).is_empty(), "nothing kept: {:?}", dir_entries(&dir));
    assert_eq!(progress.active_connections(), 0);
    let _ = std::fs::remove_dir_all(&dir);
}

#[tokio::test]
async fn oversized_playlists_are_rejected() {
    let server = Server::start().await;
    server.route("/p/s.ts", Route::new(b"x".to_vec(), "video/mp2t"));
    server.route("/p/endless.m3u8", Route { content_type: MPEGURL, ..Route::streamed(Streamed::Endless) });
    // Small, but lists too many segments.
    let many = format!("#EXTM3U\n{}#EXT-X-ENDLIST\n", "#EXTINF:1,\ns.ts\n".repeat(100_001));
    server.route("/p/many.m3u8", Route::new(many, MPEGURL));
    // Each short relative URI resolves to a copy of the 60 KiB playlist URL.
    let long = format!("/p/{}/index.m3u8", "d".repeat(60 << 10));
    let short_uris = format!("#EXTM3U\n{}#EXT-X-ENDLIST\n", "#EXTINF:1,\ns.ts\n".repeat(2_000));
    server.route(&long, Route::new(short_uris, MPEGURL));

    let dir = temp_dir("playlists");
    for (path, expected) in [
        ("/p/endless.m3u8", "/p/endless.m3u8 is larger than 16 MiB"),
        ("/p/many.m3u8", "the HLS playlist lists more than 100000 segments"),
        (long.as_str(), "the HLS playlist is too large (over 64 MiB once parsed)"),
    ] {
        let err = run_err(request(server.url(path), &dir, None), options(2)).await;
        assert!(err.ends_with(expected), "{err}");
    }
    assert_eq!(server.hits("/p/s.ts"), 0);
    assert!(dir_entries(&dir).is_empty());
    let _ = std::fs::remove_dir_all(&dir);
}

