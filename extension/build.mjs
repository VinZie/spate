// Builds the store/side-load packages:
//
//   dist/chromium/              unpacked Chromium extension (same as this folder's runtime files)
//   dist/firefox/               unpacked Firefox extension (background bundled into one classic script)
//   dist/spate-chromium-<v>.zip
//   dist/spate-firefox-<v>.zip (an unsigned .xpi is the same file)
//
// Usage: node build.mjs        (no dependencies; Node 18+)
//
// Firefox runs MV3 backgrounds as event pages listed in `background.scripts`.
// To avoid depending on module support there, the ES-module graph rooted at
// src/background.js is concatenated into one IIFE. The bundler is deliberately
// tiny and only accepts the import style used in this code base:
//   import { a, b } from './relative.js';
// and top-level names must be unique across modules (checked below).

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { deflateRawSync } from 'node:zlib';
import { crc32, writeIcons, ICON_FILES } from './scripts/make-icons.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const IMPORT_RE = /^import\s*(\{[^}]*\})?\s*(?:from\s*)?['"]([^'"]+)['"];?[ \t]*$/gm;
const DECL_RE = /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm;

/** Concatenate an ES-module graph into a single classic script. */
export function bundleModules(entryFile) {
  const ordered = [];
  const visiting = new Set();
  const done = new Set();
  const visit = (file) => {
    if (done.has(file)) return;
    if (visiting.has(file)) throw new Error(`Import cycle through ${file}`);
    visiting.add(file);
    const source = readFileSync(file, 'utf8');
    if (/\bimport\s*\(/.test(source)) throw new Error(`${file}: dynamic import() is not supported by the bundler`);
    if (/^export\s+(default|\*)/m.test(source)) throw new Error(`${file}: only named exports are supported`);
    for (const m of source.matchAll(IMPORT_RE)) {
      if (m[1] && /\bas\b/.test(m[1])) throw new Error(`${file}: "import { x as y }" is not supported`);
      if (!m[2].startsWith('.')) throw new Error(`${file}: bare import "${m[2]}" is not supported`);
      visit(resolve(dirname(file), m[2]));
    }
    visiting.delete(file);
    done.add(file);
    ordered.push({ file, source });
  };
  visit(resolve(entryFile));

  const owners = new Map();
  const parts = [];
  for (const { file, source } of ordered) {
    const rel = relative(ROOT, file).split(sep).join('/');
    for (const m of source.matchAll(DECL_RE)) {
      const prev = owners.get(m[1]);
      if (prev && prev !== rel) throw new Error(`Top-level name "${m[1]}" is defined in both ${prev} and ${rel}`);
      owners.set(m[1], rel);
    }
    const leftover = source.replace(IMPORT_RE, '');
    if (/^\s*import\s/m.test(leftover)) throw new Error(`${rel}: unsupported import statement`);
    const body = leftover
      .replace(/^export\s*\{[^}]*\};?[ \t]*$/gm, '')
      .replace(/^export\s+(?=(async\s+)?function|const|let|var|class)/gm, '');
    parts.push(`// ---- ${rel} ----\n${body.trim()}\n`);
  }
  return `// Spate background script for Firefox, generated by build.mjs from src/background.js.\n// Do not edit; edit the modules under src/ instead.\n(() => {\n'use strict';\n\n${parts.join('\n')}})();\n`;
}

// ---------------------------------------------------------------------------
// Minimal ZIP writer (deflate, UTF-8 names, fixed timestamps for reproducibility)
// ---------------------------------------------------------------------------

export function createZip(entries) {
  const DOS_TIME = 0; // 00:00:00
  const DOS_DATE = ((2025 - 1980) << 9) | (1 << 5) | 1; // 2025-01-01
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const nameBuf = Buffer.from(name, 'utf8');
    const deflated = deflateRawSync(data, { level: 9 });
    const stored = deflated.length >= data.length;
    const payload = stored ? data : deflated;
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(stored ? 0 : 8, 8);
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(payload.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    locals.push(local, nameBuf, payload);

    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(stored ? 0 : 8, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(payload.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += local.length + nameBuf.length + payload.length;
  }
  const centralBuf = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBuf, end]);
}

function listFiles(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full, base));
    else out.push(relative(base, full).split(sep).join('/'));
  }
  return out;
}

function zipDirectory(dir, zipPath) {
  const entries = listFiles(dir).map((name) => ({ name, data: readFileSync(join(dir, name)) }));
  writeFileSync(zipPath, createZip(entries));
  return entries.length;
}

// ---------------------------------------------------------------------------
// Manifest checks
// ---------------------------------------------------------------------------

/** Paths a manifest refers to (icons, pages, background scripts). */
export function manifestFiles(manifest) {
  const files = new Set(Object.values(manifest.icons || {}));
  const action = manifest.action || {};
  if (action.default_popup) files.add(action.default_popup);
  for (const p of Object.values(action.default_icon || {})) files.add(p);
  if (manifest.options_ui && manifest.options_ui.page) files.add(manifest.options_ui.page);
  const bg = manifest.background || {};
  if (bg.service_worker) files.add(bg.service_worker);
  for (const s of bg.scripts || []) files.add(s);
  return [...files];
}

function checkManifestFiles(dir, manifest) {
  const missing = manifestFiles(manifest).filter((p) => !existsSync(join(dir, p)));
  if (missing.length) throw new Error(`${dir}: manifest refers to missing files: ${missing.join(', ')}`);
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

export function build({ outDir = join(ROOT, 'dist'), log = console.log } = {}) {
  const iconsDir = join(ROOT, 'icons');
  if (!ICON_FILES.every(([name]) => existsSync(join(iconsDir, name)))) writeIcons(iconsDir);

  const chromeManifest = JSON.parse(readFileSync(join(ROOT, 'manifest.json'), 'utf8'));
  const firefoxManifest = JSON.parse(readFileSync(join(ROOT, 'manifest.firefox.json'), 'utf8'));
  firefoxManifest.version = chromeManifest.version; // manifest.json is the version source of truth
  const version = chromeManifest.version;

  rmSync(outDir, { recursive: true, force: true });
  const chromium = join(outDir, 'chromium');
  const firefox = join(outDir, 'firefox');

  // Chromium: the runtime files exactly as they are loaded unpacked.
  for (const d of ['src', 'icons']) cpSync(join(ROOT, d), join(chromium, d), { recursive: true });
  writeFileSync(join(chromium, 'manifest.json'), `${JSON.stringify(chromeManifest, null, 2)}\n`);
  checkManifestFiles(chromium, chromeManifest);

  // Firefox: same pages and modules, plus the bundled background script.
  for (const d of ['src', 'icons']) cpSync(join(ROOT, d), join(firefox, d), { recursive: true });
  rmSync(join(firefox, 'src', 'background.js'));
  const bundle = bundleModules(join(ROOT, 'src', 'background.js'));
  new vm.Script(bundle, { filename: 'background.bundle.js' }); // syntax check
  writeFileSync(join(firefox, 'src', 'background.bundle.js'), bundle);
  writeFileSync(join(firefox, 'manifest.json'), `${JSON.stringify(firefoxManifest, null, 2)}\n`);
  checkManifestFiles(firefox, firefoxManifest);

  mkdirSync(outDir, { recursive: true });
  const chromeZip = join(outDir, `spate-chromium-${version}.zip`);
  const firefoxZip = join(outDir, `spate-firefox-${version}.zip`);
  const n1 = zipDirectory(chromium, chromeZip);
  const n2 = zipDirectory(firefox, firefoxZip);
  log(`Chromium: ${relative(ROOT, chromium)}  ->  ${relative(ROOT, chromeZip)} (${n1} files)`);
  log(`Firefox:  ${relative(ROOT, firefox)}  ->  ${relative(ROOT, firefoxZip)} (${n2} files)`);
  return { chromium, firefox, chromeZip, firefoxZip, version };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    build();
  } catch (e) {
    console.error(`build failed: ${e.message}`);
    process.exit(1);
  }
}
